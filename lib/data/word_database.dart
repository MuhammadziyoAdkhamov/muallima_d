/// Har bir so'z uchun MCQ savol generatsiya qiladi.
/// Three incorrect choices are sampled from [distractorPool] when provided.
List<Question> generateQuestions(
  List<Word> words, {
  List<Word>? distractorPool,
}) {
  final random = Random();
  final questions = <Question>[];
  final candidates = distractorPool ?? words;

  for (final word in words) {
    final distractors =
        candidates
            .where((w) => w.id != word.id && w.meaning != word.meaning)
            .toList()
          ..shuffle(random);

    final wrongOptions = distractors
        .map((candidate) => candidate.meaning)
        .toSet()
        .take(3)
        .toList();
    final allOptions = [word.meaning, ...wrongOptions]..shuffle(random);

    questions.add(
      Question(
        id: word.id,
        arabic: word.arabic,
        transliteration: word.transliteration,
        correctAnswer: word.meaning,
        options: allOptions,
        type: QuestionType.mcq,
        root: word.root,
      ),
    );
  }

  return questions;
}
